-- 面经正文与投稿审核共用一张表；draft/pending 等状态不会出现在公开列表。
CREATE TABLE interviews (
    id INT PRIMARY KEY AUTO_INCREMENT,
    company VARCHAR(100) NOT NULL,
    role VARCHAR(100) NOT NULL,
    author VARCHAR(100) NOT NULL,
    cohort VARCHAR(30) NOT NULL DEFAULT '',
    date VARCHAR(30) NOT NULL DEFAULT '',
    recruitment_type VARCHAR(30) NOT NULL DEFAULT '实习',
    category VARCHAR(50) NULL,
    city VARCHAR(60) NULL,
    difficulty VARCHAR(20) NOT NULL DEFAULT '中等',
    rounds INT NOT NULL DEFAULT 1,
    round_details JSON NOT NULL,
    preparation TEXT NULL,
    summary TEXT NOT NULL,
    reflection TEXT NULL,
    tags JSON NOT NULL,
    anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    views INT NOT NULL DEFAULT 0,
    visibility VARCHAR(20) NOT NULL DEFAULT 'members',
    status VARCHAR(30) NOT NULL DEFAULT 'draft',
    submitter_id INT NULL,
    submitted_at DATETIME NULL,
    withdrawn_at DATETIME NULL,
    reviewed_by INT NULL,
    reviewed_at DATETIME NULL,
    review_note TEXT NULL,
    review_history JSON NOT NULL,
    version INT NOT NULL DEFAULT 1,
    published_at DATETIME NULL,
    created_by INT NULL,
    updated_by INT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_interview_submitter FOREIGN KEY (submitter_id) REFERENCES users(id),
    CONSTRAINT fk_interview_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),
    CONSTRAINT fk_interview_creator FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_interview_updater FOREIGN KEY (updated_by) REFERENCES users(id),
    INDEX idx_interview_status_visibility (status, visibility),
    INDEX idx_interview_cohort (cohort),
    INDEX idx_interview_recruitment_type (recruitment_type),
    INDEX idx_interview_category (category),
    INDEX idx_interview_submitter (submitter_id),
    INDEX idx_interview_published_at (published_at)
);

CREATE TABLE interview_helpful_votes (
    id INT PRIMARY KEY AUTO_INCREMENT,
    interview_id INT NOT NULL,
    user_id INT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interview_vote_interview FOREIGN KEY (interview_id) REFERENCES interviews(id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_vote_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_interview_helpful_user UNIQUE (interview_id, user_id),
    INDEX idx_interview_vote_user (user_id)
);
